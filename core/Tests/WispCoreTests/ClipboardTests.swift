import XCTest
@testable import WispCore

final class ClipboardTests: XCTestCase {
    private let t0 = Date(timeIntervalSince1970: 2_000_000)
    private var dir: URL!

    override func setUpWithError() throws {
        dir = FileManager.default.temporaryDirectory.appendingPathComponent("wisp-clipboard-\(UUID().uuidString)")
    }

    override func tearDownWithError() throws {
        try? FileManager.default.removeItem(at: dir)
    }

    private func text(_ value: String, at offset: TimeInterval = 0) -> ClipItem {
        ClipItem(kind: ClipItem.kind(of: value), text: value, image: nil, fingerprint: ClipItem.fingerprint(Data(value.utf8)), copiedAt: t0.addingTimeInterval(offset))
    }

    // MARK: Privacy

    func testPasswordManagerMarkersAreNeverCaptured() {
        let plain = ["public.utf8-plain-text", "NSStringPboardType"]
        XCTAssertTrue(ClipboardPrivacy.shouldCapture(types: plain))
        for marker in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
            "de.petermaurer.TransientPasteboardType",
        ] {
            XCTAssertFalse(ClipboardPrivacy.shouldCapture(types: plain + [marker]), marker)
            XCTAssertFalse(ClipboardPrivacy.shouldCapture(types: [marker] + plain), marker)
        }
    }

    func testEmptyPasteboardIsNotCaptured() {
        XCTAssertFalse(ClipboardPrivacy.shouldCapture(types: []))
    }

    func testMarkerMatchIsExact() {
        XCTAssertTrue(ClipboardPrivacy.shouldCapture(types: ["public.utf8-plain-text", "org.nspasteboard.concealedtype.other"]))
    }

    // MARK: Kind

    func testKindOfString() {
        XCTAssertEqual(ClipItem.kind(of: "https://example.com/a?b=1"), .url)
        XCTAssertEqual(ClipItem.kind(of: "  http://example.com\n"), .url)
        XCTAssertEqual(ClipItem.kind(of: "see https://example.com"), .text)
        XCTAssertEqual(ClipItem.kind(of: "ftp://example.com"), .text)
        XCTAssertEqual(ClipItem.kind(of: "example.com"), .text)
        XCTAssertEqual(ClipItem.kind(of: "https://"), .text)
        XCTAssertEqual(ClipItem.kind(of: "hello"), .text)
    }

    // MARK: History

    func testNewestFirstAndRecopyMovesUpWithoutDuplicating() {
        var history = ClipboardHistory()
        let a = text("alpha")
        history.insert(a)
        history.insert(text("beta", at: 1))
        history.togglePin(a.id)
        XCTAssertEqual(history.insert(text("alpha", at: 2)), [])
        XCTAssertEqual(history.items.map(\.text), ["alpha", "beta"])
        XCTAssertEqual(history.items[0].id, a.id)
        XCTAssertTrue(history.items[0].pinned)
        XCTAssertEqual(history.items[0].copiedAt, t0.addingTimeInterval(2))
    }

    func testCapEvictsOldestUnpinned() {
        var history = ClipboardHistory()
        let first = text("item-0")
        history.insert(first)
        history.togglePin(first.id)
        history.insert(text("item-1", at: 1))
        for index in 2..<ClipboardHistory.capacity {
            history.insert(text("item-\(index)", at: TimeInterval(index)))
        }
        XCTAssertEqual(history.items.count, ClipboardHistory.capacity)
        let evicted = history.insert(text("item-new", at: 500))
        XCTAssertEqual(evicted.map(\.text), ["item-1"])
        XCTAssertEqual(history.items.count, ClipboardHistory.capacity)
        XCTAssertTrue(history.items.contains { $0.id == first.id })
        XCTAssertEqual(history.items.first?.text, "item-new")
    }

    func testClearKeepsPinnedAndRemoveReturnsItem() {
        var history = ClipboardHistory()
        let keep = text("keep")
        let gone = text("gone", at: 1)
        let other = text("other", at: 2)
        [keep, gone, other].forEach { history.insert($0) }
        history.togglePin(keep.id)
        XCTAssertEqual(history.remove(gone.id)?.id, gone.id)
        XCTAssertNil(history.remove(UUID()))
        XCTAssertEqual(history.clearUnpinned().map(\.id), [other.id])
        XCTAssertEqual(history.items.map(\.id), [keep.id])
    }

    func testVisiblePinnedFirstAndSearchIgnoresCaseAndAccents() {
        var history = ClipboardHistory()
        let old = text("Reunião às 10h")
        history.insert(old)
        history.insert(text("https://example.com/reuniao", at: 1))
        history.insert(ClipItem(kind: .image, text: nil, image: "x.png", fingerprint: "img", copiedAt: t0.addingTimeInterval(2)))
        history.togglePin(old.id)
        XCTAssertEqual(history.visible(matching: "").map(\.kind), [.text, .image, .url])
        XCTAssertEqual(history.visible(matching: "REUNIAO").map(\.text), ["Reunião às 10h", "https://example.com/reuniao"])
        XCTAssertEqual(history.visible(matching: "nada"), [])
    }

    // MARK: Setting

    func testCaptureSettingDefaultsOnAndRoundTrips() throws {
        let old = try JSONDecoder().decode(WispSettings.self, from: Data(#"{"theme":"lime"}"#.utf8))
        XCTAssertTrue(old.clipboardCapture)
        var off = WispSettings.default
        off.clipboardCapture = false
        try SettingsStore(directory: dir).save(off)
        XCTAssertFalse(SettingsStore(directory: dir).settings.clipboardCapture)
    }

    // MARK: Store

    func testStoreRoundTripAndImageFiles() throws {
        let store = ClipboardStore(directory: dir)
        let id = UUID()
        let name = try store.writeImage(png: Data([1, 2, 3]), thumbnail: Data([4]), id: id)
        var history = ClipboardHistory()
        let image = ClipItem(id: id, kind: .image, text: nil, image: name, fingerprint: "f", copiedAt: t0)
        history.insert(image)
        history.insert(text("hello", at: 1))
        try store.save(history)
        XCTAssertEqual(ClipboardStore(directory: dir).load(), history)

        let fm = FileManager.default
        XCTAssertTrue(fm.fileExists(atPath: store.url(of: name).path))
        XCTAssertTrue(fm.fileExists(atPath: store.url(of: ClipItem.thumbnailName(for: name)).path))
        store.deleteFiles(of: [image])
        XCTAssertFalse(fm.fileExists(atPath: store.url(of: name).path))
        XCTAssertFalse(fm.fileExists(atPath: store.url(of: ClipItem.thumbnailName(for: name)).path))
    }

    func testCorruptHistoryIsMovedAside() throws {
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        try Data("{".utf8).write(to: dir.appendingPathComponent("history.json"))
        let store = ClipboardStore(directory: dir)
        XCTAssertEqual(store.load(), ClipboardHistory())
        XCTAssertNotNil(store.lastRecoveryNote)
        XCTAssertTrue(FileManager.default.fileExists(atPath: dir.appendingPathComponent("history.json.bad").path))
    }
}
